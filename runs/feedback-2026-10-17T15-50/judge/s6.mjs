import { chromium } from "playwright";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
p.on("console", m => { if (m.type()==="error") errs.push(m.text()); });
p.on("pageerror", e => errs.push("PAGEERR "+e.message));
await p.goto("https://patient-360.raava.dev/", { waitUntil: "networkidle", timeout: 60000 });
await p.screenshot({ path: "14-desktop-today.png" });
await p.goto("https://patient-360.raava.dev/#p-c3-P03000", { waitUntil: "networkidle" });
await p.waitForTimeout(2000);
await p.screenshot({ path: "15-desktop-c3-urgent.png", fullPage: true });
console.log("--- C3\n", (await p.innerText("main").catch(()=>p.innerText("body"))).slice(0, 3500));
await p.goto("https://patient-360.raava.dev/#patients", { waitUntil: "networkidle" });
await p.waitForTimeout(1000);
await p.getByRole("button", { name: /Glucose/ }).first().click().catch(e=>console.log("noglu", e.message));
await p.waitForTimeout(1000);
await p.locator("tbody tr").first().click().catch(e=>console.log("norow", e.message));
await p.waitForTimeout(2000);
console.log("URL", p.url());
await p.screenshot({ path: "16-desktop-glucose-patient.png", fullPage: true });
console.log("--- GLU\n", (await p.innerText("main").catch(()=>p.innerText("body"))).slice(0, 3500));
console.log("ERRS", errs.join("\n"));
await b.close();
