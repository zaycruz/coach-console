import { chromium } from "playwright";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const errs = [];
p.on("console", m => { if (m.type()==="error") errs.push(m.text()); });
p.on("pageerror", e => errs.push("PAGEERR "+e.message));
await p.goto("https://patient-360.raava.dev/#today", { waitUntil: "networkidle", timeout: 60000 });
await p.getByRole("button", { name: "Ask Ellie" }).first().click();
await p.waitForTimeout(800);
await p.getByRole("button", { name: "Who needs a call today?" }).click();
await p.waitForTimeout(15000);
await p.screenshot({ path: "12-phone-ellie-today.png" });
const inp = p.locator("input[aria-label='Ask Ellie'], input[placeholder*='Ellie']").first();
await inp.fill("Should María get a chest X-ray for her shortness of breath?");
await p.getByRole("button", { name: "Send" }).click();
await p.waitForTimeout(20000);
await p.screenshot({ path: "13-phone-ellie-clinical-q.png" });
const dlg = await p.locator("[role=dialog], aside, .ellie, #ellie").first().innerText().catch(()=>"");
console.log("--- ELLIE\n", dlg.slice(0,4000) || (await p.innerText("body")).slice(-4000));
console.log("ERRS", errs.join("\n"));
await b.close();
